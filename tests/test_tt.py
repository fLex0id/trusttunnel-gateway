#!/usr/bin/env python3
"""Тесты генераторов tt.py (без root и без сети): python3 -m unittest discover -s tests"""
import base64
import builtins
import importlib.util
import io
import json
import os
import sys
import tempfile
import unittest
import zlib
from contextlib import redirect_stdout
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = importlib.util.spec_from_file_location("tt", os.path.join(HERE, "..", "src", "py", "tt.py"))

EXPORT = '''# This file was automatically generated by endpoint
hostname = "www.example.com"
addresses = ["www.example.com:443"]
custom_sni = ""
has_ipv6 = true
username = "gw"
password = "S3cret-pass_123"
client_random_prefix = ""
skip_verification = false
certificate = """
-----BEGIN CERTIFICATE-----
MIIB
-----END CERTIFICATE-----
"""
upstream_protocol = "http2"
anti_dpi = false
name = ""
dns_upstreams = []
'''


def rd(path):
    with open(path) as fh:
        return fh.read()


def wr(path, data, mode="w"):
    with open(path, mode) as fh:
        fh.write(data)


def load(etc):
    os.environ["TT_ETC"] = etc
    mod = importlib.util.module_from_spec(SPEC)
    SPEC.loader.exec_module(mod)
    return mod


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.etc = self.tmp.name
        self.tt = load(self.etc)

    def tearDown(self):
        self.tmp.cleanup()

    def conf(self, **kw):
        with open(os.path.join(self.etc, "tt.conf"), "w") as fh:
            for k, v in kw.items():
                fh.write('%s="%s"\n' % (k, v))

    def run_cmd(self, *argv, stdin=None):
        buf = io.StringIO()
        with redirect_stdout(buf), mock.patch.object(sys, "stdin", io.StringIO(stdin or "")):
            rc = self.tt.main(["tt.py"] + list(argv))
        return rc, buf.getvalue()


class TomlTest(Base):
    def test_fallback_parser_matches_export(self):
        real_import = builtins.__import__

        def no_tomllib(name, *a, **k):
            if name == "tomllib":
                raise ImportError
            return real_import(name, *a, **k)

        with mock.patch.object(builtins, "__import__", no_tomllib):
            data = self.tt.toml_loads(EXPORT)
        self.assertEqual(data["hostname"], "www.example.com")
        self.assertEqual(data["addresses"], ["www.example.com:443"])
        self.assertIs(data["has_ipv6"], True)
        self.assertEqual(data["dns_upstreams"], [])
        self.assertIn("BEGIN CERTIFICATE", data["certificate"])
        self.assertTrue(data["certificate"].startswith("-----BEGIN"))


class KeyTest(Base):
    def test_roundtrip_key(self):
        rc, out = self.run_cmd("key-encode", stdin=EXPORT)
        self.assertEqual(rc, 0)
        key = out.strip()
        self.assertTrue(key.startswith("ttgw:"))
        self.assertLess(len(key), 1500)
        rc, out = self.run_cmd("ep", "import", key)
        self.assertEqual(rc, 0)
        self.assertIn("www.example.com:443 · gw · HTTP/2", out)
        ep = json.loads(rd(os.path.join(self.etc, "endpoint.json")))
        self.assertEqual(ep["password"], "S3cret-pass_123")
        self.assertIs(ep["has_ipv6"], False)
        self.assertNotIn("name", ep)

    def test_v2_toml_key_still_accepted(self):
        key = "ttgw:" + base64.urlsafe_b64encode(zlib.compress(EXPORT.encode(), 9)).decode().rstrip("=")
        rc, out = self.run_cmd("ep", "import", key)
        self.assertEqual(rc, 0)

    def test_broken_key(self):
        with self.assertRaises(SystemExit):
            self.run_cmd("ep", "import", "ttgw:broken!!")


class ServerTest(Base):
    def test_render_server(self):
        self.conf(DOMAIN="www.example.com", PORT="443", AUTH_CODE="404")
        out = os.path.join(self.etc, "out")
        self.run_cmd("render", "server", out)
        vpn = rd(os.path.join(out, "vpn.toml"))
        self.assertIn('listen_address = "0.0.0.0:443"', vpn)
        self.assertIn("auth_failure_status_code = 404", vpn)
        self.assertIn('server_address = "127.0.0.1:8008"', vpn)
        self.assertIn("per_client_metrics = true", vpn)
        self.assertIn("connection_establishment_timeout_secs = 10", vpn)
        hosts = rd(os.path.join(out, "hosts.toml"))
        self.assertIn('hostname = "www.example.com"', hosts)
        self.assertNotIn("reverse_proxy_hosts", hosts)
        self.assertIn("169.254.0.0/16", rd(os.path.join(out, "rules.toml")))
        self.assertIn("ipv6_available = false", vpn)   # IPv6 на выходе выключен по умолчанию
        self.conf(DOMAIN="www.example.com", IPV6_EGRESS="1")
        self.run_cmd("render", "server", out)
        self.assertIn("ipv6_available = true", rd(os.path.join(out, "vpn.toml")))


class GatewayTest(Base):
    def setUp(self):
        super().setUp()
        self.rules = os.path.join(self.etc, "rules")
        os.makedirs(self.rules)
        for _, tag, _ in self.tt.RU_SETS:
            wr(os.path.join(self.rules, tag + ".srs"), b"SRS\x01", "wb")
        self.tt.RULES_DIR = self.rules

    def test_tunnel_only(self):
        self.conf(DOH="quad9", RU_DIRECT="0")
        cfg = self.tt.build_singbox(self.tt.load_conf())
        self.assertEqual(cfg["route"]["final"], "proxy")
        self.assertEqual(cfg["dns"]["servers"][1]["server"], "9.9.9.9")
        self.assertEqual(cfg["dns"]["servers"][1]["detour"], "proxy")
        self.assertNotIn("rule_set", cfg["route"])

    def test_ru_direct_priority(self):
        self.conf(DOH="opendns", RU_DIRECT="1", RU_DNS="custom", RU_DNS_CUSTOM="https://dns.example.ru/dns-query",
                  RU_GEOIP="1", RU_GUARD="1", RU_SUFFIX="1")
        cfg = self.tt.build_singbox(self.tt.load_conf())
        outs = [(r.get("rule_set") or r.get("domain_suffix"), r.get("outbound")) for r in cfg["route"]["rules"] if r.get("outbound")]
        guard = next(i for i, (k, o) in enumerate(outs) if k == ["ru-blocked"])
        ru = next(i for i, (k, o) in enumerate(outs) if k and "geosite-category-ru" in k)
        self.assertLess(guard, ru, "заблокированные в РФ должны проверяться раньше российских")
        self.assertEqual(outs[guard][1], "proxy")
        self.assertEqual(outs[ru][1], "direct")
        tags = [s["tag"] for s in cfg["dns"]["servers"]]
        self.assertIn("dns-tunnel-boot", tags)   # DoH по имени → нужен загрузочный DNS через туннель

    def test_yandex_doh_by_ip(self):
        self.conf(DOH="quad9", RU_DIRECT="1", RU_DNS="yandex-doh")
        cfg = self.tt.build_singbox(self.tt.load_conf())
        ru = next(s for s in cfg["dns"]["servers"] if s["tag"] == "dns-ru")
        self.assertEqual((ru["server"], ru["tls"]["server_name"]), ("77.88.8.8", "common.dot.dns.yandex.net"))
        self.assertNotIn("dns-tunnel-boot", [s["tag"] for s in cfg["dns"]["servers"]])

    def test_udp_block(self):
        self.conf(DOH="cloudflare", UDP_MODE="block")
        cfg = self.tt.build_singbox(self.tt.load_conf())
        self.assertEqual(cfg["outbounds"][0]["network"], "tcp")
        self.assertEqual(cfg["route"]["rules"][-1], {"network": "udp", "action": "reject"})

    def test_wg_peers_sorted(self):
        self.conf(WG_BASE="10.9.8", WG_PORT="51820")
        wr(os.path.join(self.etc, "wg.key"), "KEY\n")
        peers = os.path.join(self.etc, "peers")
        os.makedirs(peers)
        wr(os.path.join(peers, "b.peer"), "Address=10.9.8.10\nPublicKey=PB\n")
        wr(os.path.join(peers, "a.peer"), "Address=10.9.8.2\nPublicKey=PA\nPresharedKey=K\n")
        self.tt.PEERS_DIR = peers
        out = os.path.join(self.etc, "out")
        self.run_cmd("render", "wg", out)
        wg = rd(os.path.join(out, "wg0.conf"))
        self.assertLess(wg.index("PA"), wg.index("PB"))
        self.assertIn("ListenPort = 51820", wg)
        rc, ip = self.run_cmd("next-ip")
        self.assertEqual(ip.strip(), "10.9.8.3")


if __name__ == "__main__":
    unittest.main()
